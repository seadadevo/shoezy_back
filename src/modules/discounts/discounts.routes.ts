import { Router } from "express";
import { PERMISSIONS } from "../../common/auth/rbac.constants";
import { requireAuth } from "../../common/middlewares/auth.middleware";
import { requirePermission } from "../../common/middlewares/permission.middleware";
import { validate } from "../../common/middlewares/validate.middleware";
import { DiscountsController } from "./discounts.controller";
import { createDiscountSchema, discountActionSchema, discountIdSchema, listDiscountsSchema, replaceDiscountTargetsSchema, updateDiscountSchema } from "./discounts.validation";
import { parseDiscountUpload } from "./discounts-upload.middleware";
const router = Router(); const controller = new DiscountsController(); const authorize = requirePermission(PERMISSIONS.DISCOUNTS_MANAGE_ANY);
router.get("/", validate(listDiscountsSchema), requireAuth, authorize, controller.list);
router.get("/:discountId", validate(discountIdSchema), requireAuth, authorize, controller.get);
router.post("/", requireAuth, authorize, parseDiscountUpload, validate(createDiscountSchema), controller.create);
router.patch("/:discountId", requireAuth, authorize, parseDiscountUpload, validate(updateDiscountSchema), controller.update);
router.put("/:discountId/targets", validate(replaceDiscountTargetsSchema), requireAuth, authorize, controller.replaceTargets);
router.post("/:discountId/activate", validate(discountActionSchema), requireAuth, authorize, controller.activate);
router.post("/:discountId/deactivate", validate(discountActionSchema), requireAuth, authorize, controller.deactivate);
router.post("/:discountId/archive", validate(discountActionSchema), requireAuth, authorize, controller.archive);
router.get("/:discountId/statistics", validate(discountActionSchema), requireAuth, authorize, controller.statistics);
router.delete("/:discountId", validate(discountIdSchema), requireAuth, authorize, controller.delete);
export const DiscountsRoutes = router;
