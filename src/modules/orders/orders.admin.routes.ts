import { Router } from "express";
import { PERMISSIONS } from "../../common/auth/rbac.constants";
import { requireAuth } from "../../common/middlewares/auth.middleware";
import { requirePermission } from "../../common/middlewares/permission.middleware";
import { validate } from "../../common/middlewares/validate.middleware";
import { OrdersController } from "./orders.controller";
import { listAdminOrdersSchema, orderTransitionSchema, ownOrderIdSchema, shipOrderSchema } from "./orders.validation";
import { ShippingController } from "../shipping/shipping.controller";
import { updateOrderShippingSchema } from "../shipping/shipping.validation";
const router = Router(); const controller = new OrdersController();
const shippingController = new ShippingController();
router.get("/", validate(listAdminOrdersSchema), requireAuth, requirePermission(PERMISSIONS.ORDERS_READ_ANY), controller.listAny);
router.get("/:orderId", validate(ownOrderIdSchema), requireAuth, requirePermission(PERMISSIONS.ORDERS_READ_ANY), controller.getAny);
router.post("/:orderId/confirm", validate(orderTransitionSchema), requireAuth, requirePermission(PERMISSIONS.ORDERS_MANAGE_ANY), controller.confirmAny);
router.post("/:orderId/cancel", validate(orderTransitionSchema), requireAuth, requirePermission(PERMISSIONS.ORDERS_MANAGE_ANY), controller.cancelAny);
router.post("/:orderId/ship", validate(shipOrderSchema), requireAuth, requirePermission(PERMISSIONS.ORDERS_MANAGE_ANY), controller.shipAny);
router.post("/:orderId/deliver", validate(orderTransitionSchema), requireAuth, requirePermission(PERMISSIONS.ORDERS_MANAGE_ANY), controller.deliverAny);
router.patch("/:orderId/shipping", validate(updateOrderShippingSchema), requireAuth, requirePermission(PERMISSIONS.SHIPPING_MANAGE_ANY), shippingController.updateOrderShipping);
export const AdminOrdersRoutes = router;
