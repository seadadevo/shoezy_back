import { Router } from "express";
import { PERMISSIONS } from "../../common/auth/rbac.constants";
import { requireAuth } from "../../common/middlewares/auth.middleware";
import { requirePermission } from "../../common/middlewares/permission.middleware";
import { validate } from "../../common/middlewares/validate.middleware";
import { commerceMutationRateLimit } from "../../common/middlewares/commerce-rate-limit.middleware";
import { OrdersController } from "./orders.controller";
import { createOrderSchema, listOwnOrdersSchema, orderTransitionSchema, ownOrderIdSchema, requireIdempotencyKey } from "./orders.validation";
import { ShippingController } from "../shipping/shipping.controller";
import { orderShipmentSchema } from "../shipping/shipping.validation";
import { ReturnsController } from "../returns/returns.controller";
import { createReturnSchema } from "../returns/returns.validation";
import { ExchangesController } from "../exchanges/exchanges.controller";
import { createExchangeSchema } from "../exchanges/exchanges.validation";
const router = Router(); const controller = new OrdersController();
const shippingController = new ShippingController();
const returnsController = new ReturnsController();
const exchangesController = new ExchangesController();
router.post("/", validate(createOrderSchema), requireAuth, requirePermission(PERMISSIONS.ORDERS_CREATE_OWN), commerceMutationRateLimit(20, "ORDER_RATE_LIMITED"), requireIdempotencyKey, controller.place);
router.get("/", validate(listOwnOrdersSchema), requireAuth, requirePermission(PERMISSIONS.ORDERS_READ_OWN), controller.listOwn);
router.get("/:orderId", validate(ownOrderIdSchema), requireAuth, requirePermission(PERMISSIONS.ORDERS_READ_OWN), controller.getOwn);
router.post("/:orderId/cancel", validate(orderTransitionSchema), requireAuth, requirePermission(PERMISSIONS.ORDERS_CANCEL_OWN), controller.cancelOwn);
router.get("/:orderId/shipment", validate(orderShipmentSchema), requireAuth, requirePermission(PERMISSIONS.ORDERS_READ_OWN), shippingController.getOwnShipment);
router.post("/:orderId/returns", validate(createReturnSchema), requireAuth, requirePermission(PERMISSIONS.RETURNS_CREATE_OWN), commerceMutationRateLimit(10, "RETURN_RATE_LIMITED"), returnsController.create);
router.post("/:orderId/exchanges", validate(createExchangeSchema), requireAuth, requirePermission(PERMISSIONS.EXCHANGES_CREATE_OWN), commerceMutationRateLimit(10, "EXCHANGE_RATE_LIMITED"), exchangesController.create);
export const OrdersRoutes = router;
